"""Built-in launch-configuration data for the shape-tuned SeZM Triton kernels.

This module is pure data: one nested mapping per GPU model, keyed by either
the exact device name reported by :func:`torch.cuda.get_device_name` or a
stable model-name prefix.  The query layer in :mod:`.tile_configs` prefers
an exact match, then the longest prefix ending at a space boundary.  Devices
without an entry here fall back to the conservative defaults of every kernel
family (correct on any CUDA device, merely not tuned).

Entry semantics
---------------
Every per-family table maps an exact shape key to either a launch
configuration tuple or ``None``:

- a tuple is the winning configuration measured by the sweep;
- ``None`` records that the family default won the sweep;
- an absent key means the shape was never swept on this GPU.  The freeze
  auto-tuner (:func:`.sweep_tile_configs.tune_missing_configs`) treats only
  absent keys as work.

Key conventions and value layouts are documented in :mod:`.tile_configs`;
regeneration is documented in :mod:`.sweep_tile_configs`.  Winning and
marginal schedules were confirmed at production edge counts (3e5 to 6.5e5
edges).  Decisive fused-schedule losses at wide, high-degree shapes were
recorded after width-scaled memory-safe sweeps.  ``(C_wide, lmax)``-keyed
families were measured at ``n_focus = 2``.
"""

