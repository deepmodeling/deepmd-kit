"""Test LAMMPS with a .pt2 DPA4C model that carries a long-range module.

The latent-charge module sums over every pair of atoms of a complete
non-periodic system, so ``pair_style deepmd`` runs it with non-periodic
boundaries on a single rank and rejects a periodic one. The model and the
reference values, without a cell, at the default charge state and at
``charge_spin 1.0 2.0``, are generated by
source/tests/infer/gen_dpa4c_long_range.py.
"""

import os
from pathlib import (
    Path,
)

import numpy as np
import pytest
from expected_ref import (
    read_expected_ref,
)
from lammps import (
    PyLammps,
)
from lammps_test_utils import (
    make_atomic_lammps,
)
from write_lmp_data import (
    write_lmp_data,
)

pt2_file = (
    Path(__file__).parent.parent.parent
    / "tests"
    / "infer"
    / "deeppot_dpa4c_long_range.pt2"
)
ref_file = (
    Path(__file__).parent.parent.parent
    / "tests"
    / "infer"
    / "deeppot_dpa4c_long_range.expected"
)
data_file = Path(__file__).parent / "data_dpa4c_long_range_pt2.lmp"

# Guarded with try/except because the generator only runs when PyTorch is
# built; matrices that disable PyTorch still load this file at collection time.
try:
    _ref = read_expected_ref(ref_file)
    expected_e_default = float(np.sum(_ref["default"]["expected_e"]))
    expected_f_default = _ref["default"]["expected_f"].reshape(6, 3)
    expected_e_explicit = float(np.sum(_ref["explicit"]["expected_e"]))
    expected_f_explicit = _ref["explicit"]["expected_f"].reshape(6, 3)
except FileNotFoundError:
    expected_e_default = expected_f_default = None
    expected_e_explicit = expected_f_explicit = None

box = np.array([0, 13, 0, 13, 0, 13, 0, 0, 0])
coord = np.array(
    [
        [12.83, 2.56, 2.18],
        [12.09, 2.87, 2.74],
        [0.25, 3.32, 1.68],
        [3.36, 3.00, 1.81],
        [3.51, 2.51, 2.60],
        [4.27, 3.22, 1.56],
    ]
)
# atype [0, 1, 1, 0, 1, 1] (O, H, H, O, H, H) -> LAMMPS types [1, 2, 2, 1, 2, 2]
type_OH = np.array([1, 2, 2, 1, 2, 2])


def setup_module() -> None:
    if os.environ.get("ENABLE_PYTORCH", "1") != "1":
        pytest.skip("Skip test because PyTorch support is not enabled.")
    write_lmp_data(box, coord, type_OH, data_file)


def teardown_module() -> None:
    if data_file.exists():
        os.remove(data_file)


def _lammps(boundary: str) -> PyLammps:
    if not pt2_file.is_file():
        pytest.skip(f"Skip because {pt2_file} was not generated.")
    return make_atomic_lammps(data_file, boundary=boundary, atom_map="yes")


@pytest.fixture
def lammps():
    lmp = _lammps("f f f")
    yield lmp
    lmp.close()


@pytest.fixture
def lammps_periodic():
    lmp = _lammps("p p p")
    yield lmp
    lmp.close()


def test_pair_deepmd(lammps) -> None:
    lammps.pair_style(f"deepmd {pt2_file.resolve()}")
    lammps.pair_coeff("* *")
    lammps.run(0)
    assert lammps.eval("pe") == pytest.approx(expected_e_default)
    for ii in range(6):
        assert lammps.atoms[ii].force == pytest.approx(
            expected_f_default[lammps.atoms[ii].id - 1]
        )
    lammps.run(1)


def test_pair_deepmd_charge_spin(lammps) -> None:
    lammps.pair_style(f"deepmd {pt2_file.resolve()} charge_spin 1.0 2.0")
    lammps.pair_coeff("* *")
    lammps.run(0)
    assert lammps.eval("pe") == pytest.approx(expected_e_explicit)
    for ii in range(6):
        assert lammps.atoms[ii].force == pytest.approx(
            expected_f_explicit[lammps.atoms[ii].id - 1]
        )


def test_periodic_boundary_is_rejected(lammps_periodic) -> None:
    lammps_periodic.pair_style(f"deepmd {pt2_file.resolve()}")
    lammps_periodic.pair_coeff("* *")
    with pytest.raises(Exception, match="long-range module"):
        lammps_periodic.run(0)
